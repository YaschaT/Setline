const STROKE: Record<number, number> = { 400: 1.75, 500: 2, 600: 2.25, 700: 2.5 };

/** `Image(systemName:)` with `.font(.system(size:weight:))`. */
export function SFSymbol(p: { name: string; size?: number; weight?: 400 | 500 | 600 | 700; color?: string; style?: CSSProperties }) {
  const Icon = MAP[p.name] ?? SquareDashed;
  const filled = p.name.endsWith(".fill") && !["dumbbell.fill", "person.2.fill", "lock.shield.fill"].includes(p.name);
  const size = (p.size ?? 17) * 1.15;
  return (
    <Icon
      aria-hidden
      size={size}
      strokeWidth={STROKE[p.weight ?? 400]}
      color={p.color ?? "currentColor"}
      fill={filled ? (p.color ?? "currentColor") : "none"}
      style={{ flexShrink: 0, display: "block", ...p.style }}
    />
  );
}
